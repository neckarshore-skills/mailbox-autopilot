"""Rebuild `src/mailbox_cleanup/public_suffix.dat` from a downloaded Public Suffix List.

Run it by hand, with each release, and review the result in a PR. The input comes from
https://publicsuffix.org/list/public_suffix_list.dat and nowhere else: a raw file from the
GitHub repository has no version lines, and it is refused. The host itself never touches
the network for this.

    python3 -I scripts/update_public_suffix.py public_suffix_list.dat

It keeps the ICANN section only. The private section lists tenants' own suffixes, such as
one customer's name under a hosting domain, and keeping those would hand exactly that
name back to the model as a "registrable domain" (James on #96, finding 3). Rules are
written in their ASCII form, because that is the form a sender's domain is compared in.
"""

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/mailbox_cleanup/public_suffix.dat"
MIN_RULES = 1000
BEGIN = "// ===BEGIN ICANN DOMAINS==="
END = "// ===END ICANN DOMAINS==="


def ascii_rule(rule: str) -> str:
    return ".".join(label.encode("idna").decode("ascii") for label in rule.lower().split("."))


def rules(text: str) -> list[str]:
    section = text.split(BEGIN, 1)[1].split(END, 1)[0]
    found = {
        ascii_rule(line.split()[0])
        for line in section.splitlines()
        if line.strip() and not line.startswith("//")
    }
    return sorted(found)


def check(text: str) -> tuple[list[str], list[str]]:
    """The provenance lines and the rules, or a stop: a bump may not lose either."""
    meta = [line for line in text.splitlines()[:12] if line.startswith(("// VERSION", "// COMMIT"))]
    if len(meta) != 2:
        sys.exit("no VERSION and COMMIT lines: fetch the file from publicsuffix.org")
    found = rules(text)
    if len(found) < MIN_RULES:
        sys.exit(f"only {len(found)} rules: this is not the whole list")
    return meta, found


def main(path: str) -> int:
    meta, found = check(Path(path).read_text(encoding="utf-8"))
    head = [
        "// The ICANN section of the Public Suffix List, in ASCII form. Generated by",
        "// scripts/update_public_suffix.py; do not edit by hand.",
        "// Source: https://publicsuffix.org/list/public_suffix_list.dat",
        "// This Source Code Form is subject to the terms of the Mozilla Public License,",
        "// v. 2.0. If a copy of the MPL was not distributed with this file, You can obtain",
        "// one at https://mozilla.org/MPL/2.0/.",
        *meta,
    ]
    OUT.write_text("\n".join(head + found) + "\n", encoding="ascii")
    print(f"{OUT.name}: {len(found)} rules")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
